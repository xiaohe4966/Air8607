--[[跳转到指定页面
@param string key 页面 key（见 M.pageOrder）
@param table|nil opts { replace = true } 时压栈行为关闭
@return boolean 是否切换成功
]]
function M.go(key, opts)
    local page = M.pages[key]
    if not page then
        log.warn("ui_page", "page not found:", key)
        return false
    end
    if current == key and roots[key] then return true end
    local root = ensure_page(page)
    if current and roots[current] then roots[current]:set_hidden(true) end
    root:set_hidden(false)
    if current and current ~= key and not (opts and opts.replace) then
        history[#history + 1] = current
        if #history > 32 then table.remove(history, 1) end
    end
    current = key
    M.current = key
    M.root = root
    M.widgets = page.widgets
    log.info("ui_page", "page:", key, page.name)
    return true
end

--[[返回上一页（按钮动作选「返回上一页」时调用）]]
function M.back()
    local key = table.remove(history)
    if not key then
        log.warn("ui_page", "no page history")
        return false
    end
    return M.go(key, { replace = true })
end

--[[直接切换页面，不压入返回栈]]
function M.show(key)
    return M.go(key, { replace = true })
end

--[[构建并进入启动页；在 airui.init + font_load 之后调用
@param table|nil parent 父容器，nil 表示屏幕根节点
@return table|nil root 启动页 root
]]
function M.build(parent)
    M.parent = parent
    M.go(M.startPage)
    return M.root
end

