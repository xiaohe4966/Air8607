--[[轻量开关：用两个 container 画轨道和滑块，颜色可控，
回调 on_change(state) 返回 boolean。]]
local function toggle(parent, o)
    local w, h = o.w or 70, o.h or 30
    local pad = math.max(2, math.floor(h * 0.14))
    local kd = h - pad * 2
    local state = o.checked and true or false
    local track, knob
    local function apply()
        local c = state and (o.accent or 0x22C55E) or 0x26364D
        track:set_color(c, 255)
        track:set_border_color(c, 1)
        knob:set_pos(state and (w - pad - kd) or pad, pad)
    end
    local function do_toggle()
        state = not state
        apply()
        if o.on_change then o.on_change(state) end
    end
    track = airui.container({
        parent = parent, x = o.x or 0, y = o.y or 0, w = w, h = h,
        color = 0x26364D, color_opacity = 255, radius = math.floor(h / 2),
        border_color = 0x26364D, border_width = 1, on_click = do_toggle,
    })
    knob = airui.container({
        parent = track, x = pad, y = pad, w = kd, h = kd,
        color = 0xFFFFFF, color_opacity = 255, radius = math.floor(kd / 2), on_click = do_toggle,
    })
    local handle = { track = track, knob = knob }
    function handle:get_state() return state end
    function handle:set_state(v) state = v and true or false; apply() end
    apply()
    return handle
end

